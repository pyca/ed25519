@pytest.mark.parametrize(
    ("signature", "message", "public_key", "expected"), EDGE_CASES
)
def test_checkvalid_edge_cases(signature, message, public_key, expected):
    s = binascii.unhexlify(signature)
    m = binascii.unhexlify(message)
    pk = binascii.unhexlify(public_key)
    if expected == "ok":
        ed25519.checkvalid(s, m, pk)
    elif expected == "mismatch":
        with pytest.raises(ed25519.SignatureMismatch):
            ed25519.checkvalid(s, m, pk)
    else:
        with pytest.raises(ValueError):
            ed25519.checkvalid(s, m, pk)


def test_scalarmult_B():
    for e in [0, 1, 2, 3, 31, 32, 33, 2**252, ed25519.l - 1, ed25519.l + 5]:
        expected = ed25519.scalarmult(ed25519.B, e % ed25519.l)
        assert ed25519.encodepoint(
            ed25519.scalarmult_B(e)
        ) == ed25519.encodepoint(expected)
    assert ed25519.isoncurve(ed25519.scalarmult_B(2**256 - 1))


def test_half_size():
    eight_l = 8 * ed25519.l
    for h in [0, 1, 2, ed25519.l, eight_l - 1, eight_l, 2**512 - 1] + [
        int.from_bytes(os.urandom(64), "little") for _ in range(100)
    ]:
        u, v = ed25519._half_size(h)
        assert v > 0
        assert v % 2 == 1
        assert (u - v * h) % eight_l == 0
